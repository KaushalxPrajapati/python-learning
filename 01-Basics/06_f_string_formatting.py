# F-String Formatting in Python

name = "Kaushal"
age = 19
city = "Delhi"

# Using f-strings (put 'f' before quotes and variable names inside {})
print(f"My name is {name}.")
print(f"I am {age} years old and I live in {city}.")

# Math inside f-strings
print(f"In 5 years, {name} will be {age + 5} years old.")
