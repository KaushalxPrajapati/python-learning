# Variables and Data Types in Python

# Creating variables of different types
name = "Kaushal"          # String (text)
age = 19                  # Integer (whole number)
marks = 92.5              # Float (decimal number)
is_passed = True          # Boolean (True or False)

# Printing variables and checking their data type
print("Name:", name, "-> Type:", type(name))
print("Age:", age, "-> Type:", type(age))
print("Marks:", marks, "-> Type:", type(marks))
print("Passed:", is_passed, "-> Type:", type(is_passed))
