# Comparison / Relational Operators in Python (returns True or False)

a = 15
b = 20

print("a =", a, ", b =", b)
print("---------------------")

print("Is a equal to b (a == b)?", a == b)
print("Is a not equal to b (a != b)?", a != b)
print("Is a greater than b (a > b)?", a > b)
print("Is a less than b (a < b)?", a < b)
print("Is a greater than or equal to b (a >= b)?", a >= b)
print("Is a less than or equal to b (a <= b)?", a <= b)
