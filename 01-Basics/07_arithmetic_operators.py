# Arithmetic Operators in Python

num1 = 10
num2 = 3

print("Number 1:", num1)
print("Number 2:", num2)
print("---------------------")

print("Addition (+):", num1 + num2)          # 13
print("Subtraction (-):", num1 - num2)       # 7
print("Multiplication (*):", num1 * num2)    # 30
print("Division (/):", num1 / num2)          # 3.333...
print("Floor Division (//):", num1 // num2)  # 3 (quotient without decimal)
print("Modulus (%):", num1 % num2)           # 1 (remainder)
print("Exponent (**):", num1 ** num2)        # 1000 (10 to power 3)
